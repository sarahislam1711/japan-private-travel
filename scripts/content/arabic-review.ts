/*
 * Writes docs/CONTENT.ar.md: every string with its English and Arabic side by
 * side, for the native Arabic reviewer. Generated from /content; the guard's
 * SYNC check fails when /content and this sheet disagree.
 *
 *   pnpm content:ar
 */
import { writeFileSync } from "node:fs";
import { allCopy, flatten, flattenAr, needsArabic } from "../guard/walk";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const rows = allCopy().filter((l) => needsArabic(l.copy));
const byFile = Map.groupBy(rows, (l) => l.file);

let md = `# CONTENT.ar.md — Arabic review sheet

Generated by \`pnpm content:ar\` from /content. Do not edit by hand: change the
Arabic in the module's \`.ar.ts\` mirror, then regenerate.

**For the native reviewer:** every Arabic string below is a draft (\`ard\`) until
you approve it. To approve, the line changes from \`ard(...)\` to \`arl(...)\` in its
\`.ar.ts\` file. The compliance guard blocks any Arabic DRAFT from production.

Read Family Services first (halal, bathing, guiding, transport: legal and religious
weight), then the Summer Journeys title and lede.

Status: **${rows.filter((r) => r.copy.ar?.status === "locked").length}** approved,
**${rows.filter((r) => r.copy.ar?.status === "draft").length}** draft,
**${rows.filter((r) => !r.copy.ar).length}** missing — of ${rows.length} strings.
`;

for (const [file, list] of byFile) {
  md += `\n## ${file}\n\n| Where | English | Arabic | Status |\n|---|---|---|---|\n`;
  for (const l of list!) {
    const ar = flattenAr(l.copy);
    md += `| \`${l.path}\` | ${esc(flatten(l.copy))} | <span dir="rtl" lang="ar">${ar ? esc(ar) : "—"}</span> | ${l.copy.ar ? (l.copy.ar.status === "locked" ? "approved" : "draft") : "**missing**"} |\n`;
  }
}

writeFileSync("docs/CONTENT.ar.md", md);
console.log(`docs/CONTENT.ar.md — ${rows.length} strings`);
